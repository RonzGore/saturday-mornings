// Assembles ./public for the Worker from the shared app code:
//   /            landing + sign-in       (cloud/web)
//   /app/        parent dashboard        (../apps/parent)
//   /tv/         TV app                  (../apps/tv)
//   /js, /assets shared files            (../shared)
import { cpSync, mkdirSync, rmSync, writeFileSync, copyFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { configVar } from "./config.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const cloud = join(here, "..");
const root = join(cloud, "..");
const out = join(cloud, "public");

// Where parents write with privacy questions and support requests; shown on
// /privacy and /terms. Set in wrangler.jsonc (vars.CONTACT_EMAIL), or in
// wrangler.local.jsonc when the station has one.
const CONTACT_EMAIL = configVar("CONTACT_EMAIL");
// The station's own website, if it has one: linked from the waiting-list step.
const SITE_URL = configVar("SITE_URL");
const SITE_NAME = configVar("SITE_NAME");
// Who runs the station, for the legal pages (vars.OPERATOR_NAME, OPERATOR_ADDRESS).
const OPERATOR_NAME = configVar("OPERATOR_NAME");
const OPERATOR_ADDRESS = configVar("OPERATOR_ADDRESS");
const APP_URL = configVar("APP_URL");

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const copy = (from, to) => cpSync(join(root, from), join(out, to), { recursive: true });

// Landing + sign-in
cpSync(join(cloud, "web"), out, { recursive: true });

// Shared
copy("shared/schedule.js", "js/schedule.js");
copy("shared/assets", "assets");
copyFileSync(join(cloud, "node_modules/@simplewebauthn/browser/dist/bundle/index.umd.min.js"), join(out, "js/webauthn.js"));

// Parent dashboard
copy("apps/parent", "app");

// TV app, in cloud mode
copy("apps/tv", "tv");
copy("shared/schedule.js", "tv/js/schedule.js");
copy("shared/assets", "tv/assets");
writeFileSync(join(out, "tv/js/config.js"), `// Saturday Mornings TV app: cloud mode (generated by cloud/scripts/build.mjs).
var SATURDAY_TV = { mode: "cloud", syncSeconds: 30, testMinutes: 0 };
(function () {
  var m = /[?&]test=([\\d.]+)/.exec(location.search);
  if (m) SATURDAY_TV.testMinutes = parseFloat(m[1]);
  if (/[?&]offair/.test(location.search)) SATURDAY_TV.forceOffAir = true;
})();
`);

// Contact address on the legal pages and the app's help link.
for (const page of ["privacy.html", "terms.html", "security.html", "app/setup.js"]) {
  const file = join(out, page);
  writeFileSync(file, readFileSync(file, "utf8").replaceAll("CONTACT_EMAIL", CONTACT_EMAIL || "CONTACT_EMAIL")
    .replaceAll("OPERATOR_NAME", OPERATOR_NAME || "OPERATOR_NAME").replaceAll("OPERATOR_ADDRESS", OPERATOR_ADDRESS || "OPERATOR_ADDRESS"));
}

// security.txt (RFC 9116): where to report a security problem. It must name
// an expiry date; a fresh build pushes it a year out.
if (CONTACT_EMAIL) {
  mkdirSync(join(out, ".well-known"), { recursive: true });
  const expires = new Date(Date.now() + 365 * 86400e3).toISOString().slice(0, 10) + "T00:00:00.000Z";
  const base = APP_URL ? APP_URL.replace(/\/$/, "") : "";
  writeFileSync(join(out, ".well-known/security.txt"), [
    `Contact: mailto:${CONTACT_EMAIL}`,
    `Expires: ${expires}`,
    "Preferred-Languages: en",
    ...(base ? [`Canonical: ${base}/.well-known/security.txt`, `Policy: ${base}/security#report`] : []),
    "",
  ].join("\n"));
}
// The station's own website, if it has one: a link in the top bar, an
// "Extra! Extra!" card under the pitch, and one on the waiting-list step.
{
  const file = join(out, "index.html");
  const esc = (t) => t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;");
  const url = esc(SITE_URL), name = esc(SITE_NAME || "our website");
  const parts = SITE_URL ? {
    "<!-- SITE_NAV -->": `<a class="site-nav" href="${url}">📰 <span>Read ${name}</span></a>`,
    "<!-- SITE_PROMO -->": `<a class="extra" href="${url}">
        <span class="extra-kicker">Extra! Extra!</span>
        <b class="extra-head">Read all about it</b>
        <span class="extra-body">New here? Flip through ${name}: the whole story, every feature, and the funny pages.</span>
        <span class="extra-go">Turn the page</span>
      </a>`,
    "<!-- SITE_LINK -->": ` · <a href="${url}">Read ${name}</a>`,
  } : {};
  let html = readFileSync(file, "utf8");
  for (const mark of ["<!-- SITE_NAV -->", "<!-- SITE_PROMO -->", "<!-- SITE_LINK -->"]) html = html.replace(mark, parts[mark] || "");
  writeFileSync(file, html);
}
if (!OPERATOR_NAME || !OPERATOR_ADDRESS) console.warn("warning: OPERATOR_NAME / OPERATOR_ADDRESS are not set in the wrangler config (vars); the legal pages show placeholders");
if (!CONTACT_EMAIL) console.warn("warning: CONTACT_EMAIL is not set in the wrangler config (vars); /privacy, /terms and the app's help link show a placeholder");

console.log("built", out);
